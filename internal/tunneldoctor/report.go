// Languages the report can be written in.
const (
	LangEN = "en"
	LangFA = "fa"
)

// NormalizeLang maps a ?lang= value to a supported language, English by
// default.
func NormalizeLang(l string) string {
	if strings.EqualFold(strings.TrimSpace(l), LangFA) {
		return LangFA
	}
	return LangEN
}

