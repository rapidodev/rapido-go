type rep struct {
	b    strings.Builder
	lang string
	l    map[string]string
}

func (r *rep) t(key string) string { return r.l[key] }
func (r *rep) line(s string)       { r.b.WriteString(s + "\n") }
func (r *rep) blank()              { r.b.WriteString("\n") }
func (r *rep) h(level int, s string) {
	r.blank()
	r.line(strings.Repeat("#", level) + " " + s)
	r.blank()
}

// table writes a Markdown table.
func (r *rep) table(header []string, rows [][]string) {
	r.line("| " + strings.Join(header, " | ") + " |")
	seps := make([]string, len(header))
	for i := range seps {
		seps[i] = "---"
	}
	r.line("| " + strings.Join(seps, " | ") + " |")
	for _, row := range rows {
		r.line("| " + strings.Join(row, " | ") + " |")
	}
	r.blank()
}

func f1(v float64) string { return fmt.Sprintf("%.1f", v) }
func f2(v float64) string { return fmt.Sprintf("%.2f", v) }
func opt(p *float64, format string) string {
	if p == nil {
		return "-"
	}
	return fmt.Sprintf(format, *p)
}

// BuildReport writes the Markdown report for a finished diagnosis, in "en" or
// "fa". It contains no credentials: only addresses, interface names and
// measurements.
func BuildReport(res *Result, lang string) string {
	lang = NormalizeLang(lang)
	r := &rep{lang: lang, l: labels[lang]}
	if lang == LangFA {
		r.line(`<div dir="rtl" lang="fa">`)
		r.blank()
	}
	r.line("# " + r.t("title") + ": " + res.Tunnel.Name)
	r.blank()
	r.line(fmt.Sprintf("%s: %s UTC. %s: %s - %s UTC.", r.t("generated"), res.FinishedAt.UTC().Format("2006-01-02 15:04"),
		r.t("measured"), res.StartedAt.UTC().Format("2006-01-02 15:04:05"), res.FinishedAt.UTC().Format("15:04:05")))

	r.summary(res)
	r.environment(res)
	r.plateau(res)
	r.delay(res)
	r.lossRate(res)
	r.pathSection(res)
	r.counters(res)
	r.asks(res)
	r.repro(res)

	r.blank()
	r.line("---")
	r.line(r.t("footer"))
	if lang == LangFA {
		r.blank()
		r.line("</div>")
	}
	return r.b.String()
}

func (r *rep) finding(f Finding) (title, detail string) {
	if r.lang == LangFA && f.TitleFA != "" {
		return f.TitleFA, f.DetailFA
	}
	return f.Title, f.Detail
}

func (r *rep) summary(res *Result) {
	r.h(2, "1. "+r.t("summary"))
	var important, other []Finding
	for _, f := range res.Findings {
		if f.Severity == SevInfo {
			other = append(other, f)
		} else {
			important = append(important, f)
		}
	}
	sort.SliceStable(important, func(i, j int) bool {
		return important[i].Severity == SevCritical && important[j].Severity != SevCritical
	})
	if len(important) == 0 && len(other) == 0 {
		r.line(r.t("nofind"))
		return
	}
	if len(important) == 0 {
		r.line(r.t("nofind"))
		r.blank()
	}
	for _, f := range important {
		title, detail := r.finding(f)
		r.line(fmt.Sprintf("- **%s** - %s", title, detail))
	}
	if len(other) > 0 {
		r.blank()
		r.line("**" + r.t("other") + "**")
		r.blank()
		for _, f := range other {
			title, detail := r.finding(f)
			r.line(fmt.Sprintf("- %s - %s", title, detail))
		}
	}
}

func (r *rep) environment(res *Result) {
	r.h(2, "2. "+r.t("environment"))
	e := res.Environment
	un := r.t("unknown")
	orUnknown := func(s string) string {
		if s == "" {
			return un
		}
		return "`" + s + "`"
	}
	card := func(name string, speed int) string {
		if name == "" {
			return un
		}
		if speed > 0 {
			return fmt.Sprintf("`%s`, %s %d Mbit/s", name, r.t("speed"), speed)
		}
		return fmt.Sprintf("`%s`, %s: %s", name, r.t("speed"), un)
	}
	rows := [][]string{
		{r.t("tunnel"), fmt.Sprintf("%s (#%d)", res.Tunnel.Name, res.Tunnel.ID)},
		{r.t("method"), orUnknown(firstNonEmpty(res.Tunnel.Protocol, res.Tunnel.Method))},
		{r.t("nodeaddr"), orUnknown(e.NodeAddress)},
		{r.t("relayaddr"), orUnknown(e.RelayAddress)},
		{r.t("relayv6"), orUnknown(e.RelayV6)},
		{r.t("relayv4"), orUnknown(e.RelayV4)},
		{r.t("nodev6"), orUnknown(e.NodeV6)},
		{r.t("nodev4"), orUnknown(e.NodeV4)},
	}
	if e.ControlPort > 0 {
		rows = append(rows, []string{r.t("ctrl"), fmt.Sprint(e.ControlPort)})
	}
	rows = append(rows,
		[]string{r.t("nodecard"), card(e.NodeNIC, e.NodeNICSpeed)},
		[]string{r.t("relaycard"), card(e.RelayNIC, e.RelayNICSpeed)},
		[]string{r.t("kernel"), orUnknown(e.NodeKernel) + " / " + orUnknown(e.RelayKernel)},
		[]string{r.t("probe"), fmt.Sprintf(r.t("probetext"), e.PingCount, e.PingIntervalSec)},
	)
	r.table([]string{r.t("item"), r.t("value")}, rows)
}

func firstNonEmpty(xs ...string) string {
	for _, x := range xs {
		if x != "" {
			return x
		}
	}
	return ""
}

func (r *rep) plateau(res *Result) {
	h := res.History
	r.h(2, "3. "+r.t("plateau"))
	if h.Samples == 0 {
		r.line(r.t("noevents"))
		return
	}
	r.line(fmt.Sprintf(r.t("throughput"), h.WindowHours))
	r.blank()
	rows := make([][]string, 0, len(h.Throughput))
	for _, s := range h.Throughput {
		rows = append(rows, []string{s.Label, fmt.Sprint(s.N), f1(s.P50), f1(s.P90), f1(s.P99), f1(s.Max)})
	}
	r.table([]string{r.t("series"), r.t("samples"), "p50 Mbit/s", "p90 Mbit/s", "p99 Mbit/s", "max Mbit/s"}, rows)
	if h.Plateau.Detected {
		for _, f := range res.Findings {
			if f.Code == "plateau" {
				_, detail := r.finding(f)
				r.line(detail)
			}
		}
	} else {
		r.line(r.t("noplateau"))
	}
}

func (r *rep) delay(res *Result) {
	r.h(2, "4. "+r.t("delay"))
	var rows [][]string
	add := func(dir string, end EndResult) {
		for _, fam := range []struct {
			name string
			p    *netprobe.Ping
		}{{"IPv6", end.Ping.V6}, {"IPv4", end.Ping.V4}} {
			if fam.p == nil {
				rows = append(rows, []string{dir, fam.name, "-", "-", r.t("nopings"), "-", "-", "-", "-"})
				continue
			}
			p := fam.p
			rtt := func(v float64) string {
				if p.Received == 0 {
					return "-"
				}
				return f2(v)
			}
			rows = append(rows, []string{dir, fam.name, fmt.Sprint(p.Sent), fmt.Sprint(p.Received), f1(p.LossPct) + "%", rtt(p.MinMs), rtt(p.AvgMs), rtt(p.MaxMs), rtt(p.JitterMs)})
		}
	}
	add(dirLabel(r.lang, "node"), res.Node)
	add(dirLabel(r.lang, "relay"), res.Relay)
	r.table([]string{r.t("direction"), r.t("family"), r.t("sent"), r.t("recv"), r.t("loss"), r.t("min"), r.t("avg"), r.t("max"), r.t("jitter")}, rows)

	if len(res.Node.TCP) > 0 {
		r.line("**" + r.t("tcpconn") + "**")
		r.blank()
		var tr [][]string
		for _, t := range res.Node.TCP {
			tr = append(tr, []string{"IPv" + t.Family[1:], fmt.Sprint(t.Port), fmt.Sprint(t.Attempts), fmt.Sprint(t.Successes), f2(t.MinMs), f2(t.AvgMs), f2(t.MaxMs)})
		}
		r.table([]string{r.t("family"), "Port", r.t("attempts"), r.t("ok"), r.t("min"), r.t("avg"), r.t("max")}, tr)
	}

	var mtuRows [][]string
	for _, end := range []EndResult{res.Node, res.Relay} {
		for _, m := range end.MTU {
			largest, pkt := "-", "-"
			if m.LargestOK > 0 {
				largest, pkt = fmt.Sprint(m.LargestOK), fmt.Sprint(m.PathMTU)
			}
			mtuRows = append(mtuRows, []string{dirLabel(r.lang, end.Role), "IPv" + m.Family[1:], largest, pkt, intsList(m)})
		}
	}
	if len(mtuRows) > 0 {
		r.line("**" + r.t("mtu") + "**")
		r.blank()
		r.table([]string{r.t("direction"), r.t("family"), r.t("largest"), r.t("pktsize"), r.t("tried")}, mtuRows)
	}
}

func dirLabel(lang, role string) string {
	if lang == LangFA {
		return directionFA(role)
	}
	return directionEN(role)
}

func (r *rep) lossRate(res *Result) {
	r.h(2, "5. "+r.t("lossrate"))
	if len(res.History.LossByRate) == 0 {
		r.line(r.t("nolossrate"))
		return
	}
	r.line(r.t("ratebands"))
	r.blank()
	var rows [][]string
	for _, b := range res.History.LossByRate {
		rows = append(rows, []string{bandLabel(b), fmt.Sprint(b.Samples), opt(b.V6LossPct, "%.2f"), opt(b.V4LossPct, "%.2f"), opt(b.V6RTTMs, "%.1f"), opt(b.V4RTTMs, "%.1f")})
	}
	r.table([]string{r.t("band"), r.t("samples"), r.t("v6loss"), r.t("v4loss"), r.t("v6rtt"), r.t("v4rtt")}, rows)
	for _, f := range res.Findings {
		if f.Code == "loss_vs_rate" {
			_, detail := r.finding(f)
			r.line(detail)
			r.blank()
		}
	}
	h := res.History
	r.line("**" + fmt.Sprintf(r.t("events"), h.WindowHours) + "**")
	r.blank()
	if h.OutageCount == 0 && h.Failovers == 0 && h.LossEvents == 0 {
		r.line(r.t("noops"))
		return
	}
	r.line(fmt.Sprintf("- outages: %d (%d s total, longest %d s); failovers: %d; failbacks: %d; loss events: %d; card saturated events: %d", h.OutageCount, h.DowntimeSecond, h.LongestOutage, h.Failovers, h.Failbacks, h.LossEvents, h.NICSaturated))
	if len(h.Outages) > 0 {
		r.blank()
		var rows [][]string
		for _, o := range h.Outages {
			rows = append(rows, []string{r.t("outage"), o.At.Format("2006-01-02 15:04:05"), fmt.Sprint(o.Seconds)})
		}
		r.table([]string{"", r.t("at"), r.t("seconds")}, rows)
	}
}

func (r *rep) pathSection(res *Result) {
	r.h(2, "6. "+r.t("path"))
	r.line(r.t("hops"))
	r.blank()
	found := false
	for _, end := range []EndResult{res.Node, res.Relay} {
		for _, hp := range end.Hops {
			found = true
			r.line(fmt.Sprintf("**%s - IPv%s**", dirLabel(r.lang, end.Role), hp.Family[1:]))
			r.blank()
			var rows [][]string
			for _, h := range hp.Hops {
				addr := "-"
				if h.Addr != "" {
					addr = "`" + h.Addr + "`"
				}
				avg := "-"
				if h.Reached && h.AvgMs > 0 {
					avg = f1(h.AvgMs) + " ms"
				}
				rows = append(rows, []string{fmt.Sprint(h.TTL), addr, fmt.Sprintf("%d/%d", h.Replies, h.Sent), avg})
			}
			r.table([]string{r.t("hop"), r.t("addr"), r.t("replies"), r.t("avg")}, rows)
		}
	}
	if !found {
		r.line(r.t("nopings"))
	}
	for _, f := range res.Findings {
		if strings.HasPrefix(f.Code, "hops_") || strings.HasPrefix(f.Code, "mtu_") || strings.HasPrefix(f.Code, "tcp_") || strings.HasPrefix(f.Code, "spike_") {
			title, detail := r.finding(f)
			r.line(fmt.Sprintf("- %s - %s", title, detail))
		}
	}
	r.blank()
}

func (r *rep) counters(res *Result) {
	r.line("**" + r.t("counters") + "**")
	r.blank()
	var rows [][]string
	for _, end := range []EndResult{res.Node, res.Relay} {
		if !end.Reachable || end.NIC == nil {
			continue
		}
		n := end.NIC
		retr := "-"
		if t := end.TCPStat; t != nil {
			retr = fmt.Sprintf("%d/%d (%s%%) %s; %s%% %s", t.RetransSegs, t.OutSegs, f2(t.RetransPct), r.t("window"), f2(t.TotalRetransPct), r.t("boot"))
		}
		rows = append(rows, []string{
			faOrEN(r.lang, end.Role), "`" + n.Name + "`",
			fmt.Sprintf("%d/%d", n.RxErrors, n.TxErrors), fmt.Sprintf("%d/%d", n.RxDropped, n.TxDropped), fmt.Sprint(n.RxMissed),
			fmt.Sprintf("%d (%s: %d)", n.QdiscDropped, r.t("boot"), n.TotalQdiscDropped), retr,
		})
	}
	if len(rows) == 0 {
		r.line(r.t("nopings"))
		r.blank()
		return
	}
	r.table([]string{r.t("direction"), r.t("card"), "errors rx/tx", "dropped rx/tx", "missed rx", "qdisc drops", r.t("retrans")}, rows)
	for _, f := range res.Findings {
		if strings.HasPrefix(f.Code, "nic_") || strings.HasPrefix(f.Code, "retrans_") || strings.HasPrefix(f.Code, "ha_") {
			title, detail := r.finding(f)
			r.line(fmt.Sprintf("- %s - %s", title, detail))
		}
	}
	r.blank()
}

func faOrEN(lang, role string) string {
	if lang == LangFA {
		return faEnd(role)
	}
	return role
}

// Questions returns the questions for the network team that the data raises,
// numbered from one by the caller. They are questions, never claims.
func Questions(res *Result, lang string) []string {
	fa := NormalizeLang(lang) == LangFA
	pick := func(en, faText string) string {
		if fa {
			return faText
		}
		return en
	}
	e := res.Environment
	relay := firstNonEmpty(e.RelayV6, e.RelayV4, e.RelayAddress)
	node := firstNonEmpty(e.NodeV6, e.NodeV4, e.NodeAddress)
	var qs []string

	if res.History.Plateau.Detected {
		level := res.History.Plateau.LevelMbps
		qs = append(qs, pick(
			fmt.Sprintf("Is any rate limit, shaper or policer applied to %s or %s (per address, port, VLAN or flow)? Our samples show traffic flat at about %.0f Mbit/s. What are the configured rate and burst size?", relay, node, level),
			fmt.Sprintf("آیا روی %s یا %s (برای هر آدرس، پورت، VLAN یا فلو) محدودیت نرخ، shaper یا policer اعمال شده است؟ نمونه‌های ما ترافیک را حدود %.0f Mbit/s ثابت نشان می‌دهند. نرخ و burst تنظیم‌شده چقدر است؟", relay, node, level)))
	} else {
		qs = append(qs, pick(
			fmt.Sprintf("Is any rate limit, shaper or policer applied to %s or %s? If so, what are the configured rate and burst size?", relay, node),
			fmt.Sprintf("آیا روی %s یا %s محدودیت نرخ، shaper یا policer اعمال شده است؟ اگر هست، نرخ و burst تنظیم‌شده چقدر است؟", relay, node)))
	}

	lossSeen := false
	for _, end := range []EndResult{res.Node, res.Relay} {
		for _, p := range []*netprobe.Ping{end.Ping.V6, end.Ping.V4} {
			if p != nil && p.LossPct > 0 {
				lossSeen = true
			}
		}
	}
	h := res.History
	if (h.V6LossPct != nil && *h.V6LossPct > 0) || (h.V4LossPct != nil && *h.V4LossPct > 0) {
		lossSeen = true
	}
	if lossSeen {
		qs = append(qs, pick(
			fmt.Sprintf("Packet loss was measured between %s and %s (tables above). Please check the counters and queues (drops, errors, discards, buffer overruns) of every interface and switch port on the path between the two servers for the time of this report (measurement time at the top, and the last 24 h for the history tables), and tell us whether any of them was close to its capacity then.", node, relay),
			fmt.Sprintf("بین %s و %s افت بسته اندازه‌گیری شد (جدول‌های بالا). لطفاً شمارنده‌ها و صف‌ها (drop، error، discard، buffer overrun) همهٔ اینترفیس‌ها و پورت‌های سوئیچ مسیر بین دو سرور را برای زمان این گزارش (زمان اندازه‌گیری در بالا و ۲۴ ساعت گذشته برای جدول‌های تاریخچه) بررسی کنید و بگویید آیا در آن زمان‌ها ظرفیت هیچ‌کدام نزدیک پر شدن بوده است یا نه.", node, relay)))
	}

	if mtuBelowStandard(res) {
		qs = append(qs, pick(
			"The don't-fragment probe found a path MTU below 1500 on part of the path (table above). What is the MTU configured along this path, and are ICMP \"fragmentation needed\" / \"packet too big\" messages allowed through?",
			"بررسی don't-fragment در بخشی از مسیر MTU کمتر از ۱۵۰۰ نشان داد (جدول بالا). MTU تنظیم‌شده در طول این مسیر چقدر است و آیا پیام‌های ICMP «fragmentation needed» / «packet too big» عبور داده می‌شوند؟"))
	}

	if res.Environment.RelayV6 != "" && res.Environment.RelayV4 != "" && res.Node.Ping.V6 != nil && res.Node.Ping.V4 != nil && res.Node.Ping.V6.Received > 0 && res.Node.Ping.V4.Received > 0 {
		a, b := res.Node.Ping.V6.AvgMs, res.Node.Ping.V4.AvgMs
		if a > 0 && b > 0 && (a > 1.2*b || b > 1.2*a) {
			qs = append(qs, pick(
				fmt.Sprintf("The round trip from the node is %.1f ms over IPv6 and %.1f ms over IPv4 to the same relay. Are the two address families routed differently inside the datacenter, and is that expected?", a, b),
				fmt.Sprintf("زمان رفت‌وبرگشت از نود به همین رله روی IPv6 برابر %.1f ms و روی IPv4 برابر %.1f ms است. آیا دو خانوادهٔ آدرس در داخل دیتاسنتر مسیر متفاوتی دارند و این مورد انتظار است؟", a, b)))
		}
	}

	if res.History.OutageCount > 0 || res.History.Failovers > 0 {
		qs = append(qs, pick(
			fmt.Sprintf("The relay stopped answering %d time(s) and traffic failed over %d time(s) in the last %d h (times in the outage table above). Was there maintenance, a link flap or a routing change at those times?", res.History.OutageCount, res.History.Failovers, res.History.WindowHours),
			fmt.Sprintf("رله %d بار پاسخ نداد و ترافیک %d بار در %d ساعت گذشته به مسیر پشتیبان رفت (زمان‌ها در جدول قطعی‌ها). آیا در آن زمان‌ها نگهداری، قطع‌وصل لینک یا تغییر مسیریابی انجام شده است؟", res.History.OutageCount, res.History.Failovers, res.History.WindowHours)))
	}

	qs = append(qs,
		pick("Which port speed is configured for these two servers, and is it shared with other customers?",
			"سرعت پورت تنظیم‌شده برای این دو سرور چقدر است و آیا با مشتریان دیگر مشترک است؟"),
		pick("Are there per-protocol or per-flow limits or protections on this path (for example for GRE, UDP, IPv6, or connection-tracking / DDoS filtering) that could treat this traffic differently from plain TCP?",
			"آیا روی این مسیر محدودیت یا حفاظت مبتنی بر پروتکل یا فلو وجود دارد (مثلاً برای GRE، UDP، IPv6 یا connection-tracking / فیلتر DDoS) که ممکن است این ترافیک را متفاوت از TCP ساده رفتار کند؟"),
	)
	return qs
}

// mtuBelowStandard reports whether any end saw a don't-fragment payload size
// below the standard 1500-byte packet answered, while plain pings work.
func mtuBelowStandard(res *Result) bool {
	for _, end := range []EndResult{res.Node, res.Relay} {
		for _, m := range end.MTU {
			standard := 1472
			ping := end.Ping.V4
			if m.Family == "v6" {
				standard, ping = 1452, end.Ping.V6
			}
			if m.LargestOK < standard && ping != nil && ping.Received > 0 {
				return true
			}
		}
	}
	return false
}

func (r *rep) asks(res *Result) {
	r.h(2, "7. "+r.t("ask"))
	r.line(r.t("qlead"))
	r.blank()
	for i, q := range Questions(res, r.lang) {
		r.line(fmt.Sprintf("%d. %s", i+1, q))
	}
	r.blank()
}

func (r *rep) repro(res *Result) {
	r.h(2, "8. "+r.t("repro"))
	e := res.Environment
	r.line(r.t("cmds"))
	r.blank()
	r.line("```")
	node := func(s string) { r.line("[node]  " + s) }
	relay := func(s string) { r.line("[relay] " + s) }
	if e.RelayV6 != "" {
		node(fmt.Sprintf("ping -6 -c %d -i %.1f -q %s", e.PingCount, e.PingIntervalSec, e.RelayV6))
	}
	if e.RelayV4 != "" {
		node(fmt.Sprintf("ping -4 -c %d -i %.1f -q %s", e.PingCount, e.PingIntervalSec, e.RelayV4))
	}
	if e.NodeV6 != "" {
		relay(fmt.Sprintf("ping -6 -c %d -i %.1f -q %s", e.PingCount, e.PingIntervalSec, e.NodeV6))
	}
	if e.NodeV4 != "" {
		relay(fmt.Sprintf("ping -4 -c %d -i %.1f -q %s", e.PingCount, e.PingIntervalSec, e.NodeV4))
	}
	if e.RelayV4 != "" {
		node(fmt.Sprintf("ping -4 -c 2 -M do -s %d %s   # sizes: %s", mtuSizes4[0], e.RelayV4, intListPlain(mtuSizes4)))
		node(fmt.Sprintf("ping -4 -c %d -t <1..%d> %s   # one run per hop limit", hopProbes, maxHops, e.RelayV4))
	}
	if e.RelayV6 != "" {
		node(fmt.Sprintf("ping -6 -c 2 -M do -s %d %s   # sizes: %s", mtuSizes6[0], e.RelayV6, intListPlain(mtuSizes6)))
		node(fmt.Sprintf("ping -6 -c %d -t <1..%d> %s   # one run per hop limit", hopProbes, maxHops, e.RelayV6))
	}
	if e.ControlPort > 0 {
		node(fmt.Sprintf("bash -c 'exec 3<>/dev/tcp/<relay address>/%d'   # TCP connect, timed", e.ControlPort))
	}
	r.line("[both]  /proc/net/snmp (Tcp: OutSegs, RetransSegs), /sys/class/net/<card>/statistics/*, tc -s qdisc show dev <card>   # read before and after")
	r.line("```")
	r.blank()
	r.line(r.t("extra"))
	r.blank()
	r.line("```")
	if relay := firstNonEmpty(e.RelayV4, e.RelayV6); relay != "" {
		r.line(fmt.Sprintf("mtr -rwzc 100 %s", relay))
		r.line(fmt.Sprintf("iperf3 -c %s -P 4 -t 30      # and with -R for the other direction", relay))
	}
	r.line("```")
}

func intListPlain(v []int) string {
	s := make([]string, len(v))
	for i, x := range v {
		s[i] = fmt.Sprint(x)
	}
	return strings.Join(s, ",")
}
